"""The site as plain text for AI assistants: `/llms.txt` and the `/api/doc/` pages.

An assistant that can fetch a URL can read this site without a browser and without
an MCP server: `/llms.txt` (the llmstxt.org convention) says what the site is and
how its URLs work, `/api/search.md` (server/service.mjs) searches, and the pages
written here hold each OPEN document's text, one Markdown file per PDF page, which
is what a search hit points at. All static, generated by `stage.py` from the same
`dist/index/` the viewer reads, so it costs the server nothing and adds no code
path to it.

A RESTRICTED document gets a line in `/api/doc/index.md` and nothing else: no
directory, no page, no word of its text. `check_served.py` refuses a tree where
that does not hold.

Layout, under the served tree:

    llms.txt
    robots.txt                      Disallow: /api/
    api/doc/index.md                every document, restricted ones unlinked
    api/doc/not_found.md            the same list, served with a 404 by Caddy
    api/doc/<stem>/index.md         one document: metadata, links, its pages
    api/doc/<stem>/p/<n>.md         the text of page n

`<stem>` is the PDF's file name without `.pdf`, the one name a document keeps
across rebuilds (the numeric id shifts when a document is added). `apiDocHref`
in src/paths.js spells the same scheme for the search service.

Module imported, not run. Standard library only.

Written by Claude Code (Opus 5.5).
"""

from __future__ import annotations

import json
import shutil
from collections import Counter
from pathlib import Path
from urllib.parse import quote

from lib.atomic import open_atomic

API_DOC = Path("api") / "doc"
# The first characters of a page shown in a document's page list: enough to tell
# a table of contents from a bibliography, short enough that a 400-page report's
# list stays one fetch.
PAGE_PREVIEW_CHARS = 90
FIGURE_NOTE = "[Figure description, written by an AI model from the image, not the document's own words]"


def with_byline(meta: dict, body: str) -> str:
    """`body` under the index's byline (lib/site_config.byline), when it carries one."""
    line = meta.get("byline", "")
    return f"{line}\n\n{body}" if line else body


def stem_of(file: str) -> str:
    """The name a document's pages live under: its file name without `.pdf`."""
    return file[:-4] if file.lower().endswith(".pdf") else file


def doc_href(file: str, page: int | None = None) -> str:
    """Root-relative URL of a document's index or one of its pages (src/paths.js: apiDocHref)."""
    href = f"api/doc/{quote(stem_of(file), safe='')}"
    return href if page is None else f"{href}/p/{page}"


def view_href(doc_id: int | str, file: str, page: int | None = None) -> str:
    """The viewer link a person opens (src/paths.js: viewHref)."""
    href = f"view.html?doc={doc_id}&file={quote(file, safe='')}"
    return href if page is None else f"{href}&p={page}"


def metadata_lines(doc: dict, fields: list[str], separator: str) -> list[str]:
    """A document's facets as `- field: value` lines, blanks and `-` left out."""
    lines = []
    for field in fields:
        values = [v.strip() for v in str(doc.get(field) or "").split(separator) if v.strip()]
        values = [v for v in values if v != "-"]
        if values:
            lines.append(f"- {field}: {', '.join(values)}")
    for extra in ("doi", "isbn", "source_url"):
        value = str(doc.get(extra) or "").strip()
        if value and value != "-":
            lines.append(f"- {extra}: {value}")
    return lines


def page_texts(chunks: list[dict], page_count: int) -> dict[int, list[str]]:
    """Each page's passages, in reading order.

    A passage spanning two pages is listed on both, marked on the second, so a
    page read alone never starts mid-sentence without saying so. A described
    figure is marked as the model's words rather than the document's.
    """
    pages: dict[int, list[str]] = {n: [] for n in range(1, page_count + 1)}
    for chunk in chunks:
        text = (chunk.get("text") or "").strip()
        if not text:
            continue
        if chunk.get("figure"):
            text = f"{FIGURE_NOTE}\n\n{text}"
        spanned = chunk.get("pages") or []
        for at, page in enumerate(spanned):
            if page not in pages:
                pages[page] = []
            prefix = f"(continued from p. {spanned[0]})\n\n" if at else ""
            pages[page].append(prefix + text)
    return pages


def write_if_changed(path: Path, body: str) -> bool:
    """Write `body` unless the file already holds it, so rsync sees nothing new."""
    if path.is_file() and path.read_text(encoding="utf-8") == body:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    with open_atomic(path, encoding="utf-8") as out:
        out.write(body)
    return True


def doc_list(documents: list[dict], tiers: dict[str, str], at) -> list[str]:
    """One line per document, linked when open, flagged when restricted."""
    lines = []
    for doc in documents:
        title = doc.get("title") or doc["file"]
        facts = ", ".join(str(doc.get(f)) for f in ("issuer", "year", "language") if doc.get(f))
        facts = f" ({facts})" if facts else ""
        if tiers.get(doc["file"]) == "restricted":
            lines.append(f"- {title}{facts}: restricted, no text here; "
                         f"a person can read it in the viewer at {at(view_href(doc['id'], doc['file']))}")
        else:
            lines.append(f"- [{title}]({at(doc_href(doc['file']))}){facts}")
    return lines


def render_doc_index(doc: dict, pages: dict[int, list[str]], page_count: int,
                     fields: list[str], separator: str, at) -> str:
    """One open document: what it is, where it is, and what each page starts with."""
    lines = [f"# {doc.get('title') or doc['file']}", ""]
    lines += metadata_lines(doc, fields, separator)
    lines += [
        f"- pages: {page_count}",
        f"- PDF: {at('pdf/' + quote(doc['file'], safe=''))}",
        f"- viewer: {at(view_href(doc['id'], doc['file']))}",
        "",
        "## Pages",
        "",
    ]
    for page in sorted(pages):
        first = " ".join(" ".join(pages[page]).split())[:PAGE_PREVIEW_CHARS]
        lines.append(f"- [p. {page}]({at(doc_href(doc['file'], page))}): {first or '(no text)'}")
    return "\n".join(lines) + "\n"


def render_page(doc: dict, page: int, passages: list[str], page_count: int, at) -> str:
    """The text of one page, with the links an assistant needs to move or cite."""
    title = doc.get("title") or doc["file"]
    nav = [f"document: {at(doc_href(doc['file']))}",
           f"viewer (for a person): {at(view_href(doc['id'], doc['file'], page))}"]
    if page > 1:
        nav.append(f"previous: {at(doc_href(doc['file'], page - 1))}")
    if page < page_count:
        nav.append(f"next: {at(doc_href(doc['file'], page + 1))}")
    body = "\n\n".join(passages) if passages else (
        "(No text was extracted from this page: it may be blank, an image, or a figure "
        "nobody described. The viewer shows it as printed.)")
    return f"# {title}, p. {page} of {page_count}\n\n" + "\n".join(f"- {n}" for n in nav) + f"\n\n{body}\n"


def stage_api_docs(index_dir: Path, www: Path, tiers: dict[str, str], site_url: str) -> tuple[int, int]:
    """Write `api/doc/` under `www` from the built index, removing what it no longer holds.

    Parameters
    ----------
    index_dir
        The FULL index (`dist/index`), whose `doc/<id>.json` still hold every
        chunk's text; restricted documents are skipped here, never stripped.
    www
        The served tree.
    tiers
        `stage.read_access`: file name to "open" or "restricted".
    site_url
        `[site] url`, or "" for root-relative links.

    Returns
    -------
    tuple[int, int]
        Open documents written, page files written or changed.
    """
    meta_path = index_dir / "meta.json"
    if not meta_path.exists():
        return 0, 0
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    documents = meta.get("documents", [])
    fields = [f for f in meta.get("facet_fields", []) if f != "access"]
    separator = meta.get("separator", ";")
    root = www / API_DOC
    at = (lambda path: f"{site_url}/{path}") if site_url else (lambda path: f"/{path}")

    stems = Counter(stem_of(d["file"]) for d in documents)
    clashes = sorted(s for s, n in stems.items() if n > 1)
    if clashes:
        raise ValueError(f"two documents share an api/doc name once .pdf is dropped: {clashes}")

    keep: set[Path] = set()
    written = changed = 0
    for doc in documents:
        if tiers.get(doc["file"]) == "restricted":
            continue
        source = index_dir / "doc" / f"{doc['id']}.json"
        if not source.exists():
            continue
        chunks = json.loads(source.read_text(encoding="utf-8")).get("chunks", [])
        page_count = int(doc.get("pages") or 0) or max((p for c in chunks for p in c.get("pages", [])), default=0)
        pages = page_texts(chunks, page_count)
        folder = root / stem_of(doc["file"])
        keep.add(folder)
        changed += write_if_changed(folder / "index.md", with_byline(
            meta, render_doc_index(doc, pages, page_count, fields, separator, at)))
        wanted = {f"{page}.md" for page in pages}
        for page, passages in pages.items():
            changed += write_if_changed(folder / "p" / f"{page}.md", with_byline(
                meta, render_page(doc, page, passages, max(page_count, page), at)))
        for stale in (folder / "p").glob("*") if (folder / "p").is_dir() else ():
            if stale.name not in wanted:
                stale.unlink()
        written += 1

    listing = doc_list(documents, tiers, at)
    intro = ("Every document this site serves. Open documents link to their text, one "
             "Markdown page per PDF page. Restricted ones are only readable by a person, "
             "page by page, in the viewer.")
    write_if_changed(root / "index.md", with_byline(
        meta, f"# Documents\n\n{intro}\n\n" + "\n".join(listing) + "\n"))
    write_if_changed(root / "not_found.md", with_byline(
        meta, "# Not found\n\nNo document or page at this address. "
        "The documents are listed below; a page number past the end of a "
        f"document has no page either.\n\n{intro}\n\n" + "\n".join(listing) + "\n"))
    # A document removed, renamed or restricted since the last stage: its folder goes.
    for entry in root.iterdir():
        if entry.is_dir() and entry not in keep:
            shutil.rmtree(entry)
    return written, changed


def facet_values(documents: list[dict], field: str, separator: str) -> list[tuple[str, int]]:
    """The values one facet takes across the corpus, most documents first."""
    counts: Counter[str] = Counter()
    for doc in documents:
        for value in str(doc.get(field) or "").split(separator):
            if value.strip() and value.strip() != "-":
                counts[value.strip()] += 1
    return sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))


def render_llms_txt(site: dict, meta: dict, tiers: dict[str, str]) -> str:
    """`/llms.txt`: what the site is and how an assistant reads and searches it."""
    url = site["url"]
    at = (lambda path: f"{url}/{path}") if url else (lambda path: f"/{path}")
    documents = meta.get("documents", [])
    separator = meta.get("separator", ";")
    restricted = sum(1 for d in documents if tiers.get(d["file"]) == "restricted")
    ranges = set(meta.get("range_fields", []))
    filter_lines = []
    for field in meta.get("facet_fields", []):
        if field in ranges:
            years = sorted(int(v) for v, _ in facet_values(documents, field, separator) if v.isdigit())
            if years:
                filter_lines.append(f"- `{field}`: a range, `{field}=2015-2020`, `{field}=2015-` or "
                                    f"`{field}=-2020` (from {years[0]} to {years[-1]})")
            continue
        values = facet_values(documents, field, separator)
        if values:
            listed = ", ".join(f"`{v}` ({n})" for v, n in values)
            filter_lines.append(f"- `{field}` (repeat the parameter for several values): {listed}")
    tiers_vocab = meta.get("guideline_tiers") or []
    if tiers_vocab:
        filter_lines.append(f"- `level`: {', '.join(f'`{t}`' for t in tiers_vocab[:-1])} narrow to "
                            "documents of that tier and the narrower ones; `all` (the default) "
                            "keeps everything")
    example = at("api/search.md?q=" + quote("first-line treatment", safe=""))

    sections = [
        # The llmstxt.org format wants the name as the H1, so the byline is the H1.
        f"# {meta.get('byline') or site['name']}",
        "",
        f"> {site['description']} {len(documents)} documents (PDF), searchable together by "
        "meaning across languages: a question in one language finds passages in another. "
        "No AI writes the answers: the search returns the documents' own passages.",
        "",
        "Please do not crawl. Every search costs the small server an embedding call, and "
        "it is rate-limited per IP; ask a few targeted questions instead. "
        f"The software is open source: {site['repo_url']}",
        "",
        "## Search",
        "",
        f"- `GET {at('api/search.md')}?q=<question>`: the best passages for a question, as "
        "Markdown, best first, each with its document's metadata, its page and links. "
        f"Example: {example}",
        "- The question is plain prose, from 5 to 512 characters. `A | B` averages two "
        "phrasings, `-(C)` subtracts a topic.",
        "- It takes exactly the parameters of the search page's own URL, so a link a person "
        "copied from the site's address bar works here with its path changed to `/api/search.md`.",
        "- Optional filters:",
        *[f"  {line}" for line in filter_lines],
        "- Optional ranking choices: `bm25=1` (also reward the question's exact words), "
        "`recent=1` (favour recent documents), `norefs=1` (push bibliographies down), "
        "`figures=exclude|only|tables|images` (described figures are included by default).",
        "",
        "## Read",
        "",
        f"- [{at('api/doc/')}]({at('api/doc/')}): every document, with links to the open ones.",
        f"- `{at('api/doc/<name>')}`: one document's metadata, its PDF, and its pages with "
        "their first words. `<name>` is the PDF's file name without `.pdf`, URL-encoded.",
        f"- `{at('api/doc/<name>/p/<n>')}`: the text of page n. A search hit links to its page.",
        "- An address with no page answers 404 with the full document list.",
        "",
        "The text was extracted from the PDFs (with OCR for scanned pages), so tables and "
        "layout are approximate: the PDF is the reference. Passages marked as a figure "
        "description were written by an AI model from the image.",
        "",
    ]
    if restricted:
        sections += [
            "## Restricted documents",
            "",
            f"{restricted} documents may only be read by a person, page by page, in the "
            "viewer: they are never offered whole, and their text is not published here. "
            "A search may still quote one passage of them, with a viewer link.",
            "",
        ]
    sections += [
        "## Linking a person to a passage",
        "",
        f"Give the viewer link from a search hit or a page (`{at('view.html')}?doc=...`): it opens "
        "the PDF at that page with the passage highlighted. Cite the document's title, issuer, "
        "year and page.",
        "",
    ]
    return "\n".join(sections)


# The user agents an assistant fetches with when a PERSON asked it something, as
# opposed to the crawlers that index or train. They honour robots.txt (Anthropic
# documents it for Claude-User), so a bare `Disallow: /api/` would make them refuse
# the very pages llms.txt sends them to. A group naming an agent replaces the `*`
# group for that agent, so these are let in and every other crawler stays out.
ASSISTANT_AGENTS = ("Claude-User", "ChatGPT-User", "Perplexity-User", "MistralAI-User")

ROBOTS_TXT = """# The /api/ paths are written for AI assistants a person asked (see /llms.txt),
# and every /api/search.md costs an embedding call: not for indexing.
User-agent: *
Disallow: /api/

# Assistants fetching on behalf of the person who asked them.
""" + "".join(f"User-agent: {agent}\n" for agent in ASSISTANT_AGENTS) + "Allow: /\n"
